/**
 * Normalizes user input for Threads profile links.
 * Accepts:
 *  - username without @ (e.g. "alex")
 *  - username with @ (e.g. "@alex")
 *  - full or partial URLs:
 *      threads.net/@alex, https://threads.net/@alex,
 *      https://www.threads.net/@alex, https://threads.com/@alex
 * Returns canonical https://www.threads.net/@username
 */
export function normalizeThreadsUrl(input?: string): string {
  if (!input) return '';
  const trimmed = input.trim();
  if (!trimmed) return '';

  // Extract username if URL is provided
  const urlMatch = trimmed.match(/(?:threads\.(?:net|com))\/(?:@)?([a-zA-Z0-9._]+)/i);
  if (urlMatch && urlMatch[1]) {
    return `https://www.threads.net/@${urlMatch[1]}`;
  }

  // Handle bare username (with or without @)
  const cleanHandle = trimmed.replace(/^@/, '').replace(/[^a-zA-Z0-9._]/g, '');
  return cleanHandle ? `https://www.threads.net/@${cleanHandle}` : '';
}

